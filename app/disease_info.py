# =========================================================
# INFORMATION RETRIEVAL
# =========================================================

def get_disease_info(class_name):

    # Healthy class
    if class_name.lower().endswith("___healthy"):

        return {
            "healthy": True,

            "about": (
                "The uploaded leaf was classified as healthy. "
                "No disease class was identified by the model."
            ),

            "symptoms": [],

            "actions": [
                "Continue monitoring the plant regularly",
                "Maintain appropriate watering",
                "Maintain balanced nutrition",
                "Inspect periodically for pests or new symptoms"
            ],

            "prevention": [
                "Maintain good plant hygiene",
                "Provide appropriate spacing and airflow",
                "Avoid unnecessary foliage wetness",
                "Remove damaged plant material when needed"
            ]
        }

    # Disease found in database
    information = DISEASE_INFO.get(
        class_name
    )

    if information:

        return {
            "healthy": False,
            **information
        }

    # Fallback
    return {
        "healthy": False,

        "about": (
            "PlantVision detected a possible plant condition, "
            "but detailed guidance is not currently available "
            "for this class."
        ),

        "symptoms": [
            "Inspect the leaf carefully for visible abnormalities"
        ],

        "actions": [
            "Monitor the plant for progression",
            "Consider consulting a local agricultural expert"
        ],

        "prevention": [
            "Maintain good plant hygiene",
            "Use appropriate watering and nutrition practices"
        ]
    }